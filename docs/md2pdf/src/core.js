/**
 * Constructs the final A4 pdfMake docDef
 */
function buildDocDef(pdfContent) {
  return {
    pageSize: 'A4',
    pageOrientation: 'portrait',
    pageMargins: [42.5, 34, 42.5, 34], // 15mm left/right, 12mm top/bottom
    content: pdfContent,
    defaultStyle: {
      fontSize: 9.5,
      lineHeight: 1.15,
      color: '#000000'
    },
    footer: function (currentPage) {
      return {
        text: currentPage.toString(),
        alignment: 'center',
        fontSize: 9,
        margin: [0, 10, 0, 0]
      };
    }
  };
}

