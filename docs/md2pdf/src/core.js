'use strict';

/**
 * Preprocess markdown to convert \break and \hfill into HTML equivalents
 */
function preprocessMarkdown(md, markedInstance) {
  if (!md) return '';

  const parseInline = (markedInstance && markedInstance.parseInline)
    ? markedInstance.parseInline.bind(markedInstance)
    : (text => text);

  const lines = md.replace(/\r\n/g, '\n').split('\n');
  const processed = [];

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];

    // Handle \break (page break)
    if (/^\s*\\break\s*$/.test(line)) {
      processed.push('\n\n<div style="page-break-before: always; height: 0;">&#8203;</div>\n\n');
      continue;
    }

    // Handle \hfill (push to right margin)
    if (line.includes('\\hfill')) {
      const parts = line.split('\\hfill');

      // Check if list item
      const listMatch = line.match(/^(\s*[-*+]\s+)(.*)$/);
      if (listMatch) {
        const prefix = listMatch[1];
        const content = listMatch[2];
        const contentParts = content.split('\\hfill');
        const leftHtml = parseInline(contentParts[0].trim());
        const rightHtml = parseInline(contentParts[1].trim());

        processed.push(
          `${prefix}<table style="width: 100%; border: none;"><tr><td style="border: none; padding: 0;">${leftHtml}</td><td style="border: none; padding: 0; text-align: right;">${rightHtml}</td></tr></table>`
        );
        continue;
      }

      // Regular line or heading
      const leftHtml = parseInline(parts[0].trim());
      const rightHtml = parseInline(parts[1].trim());
      processed.push(
        `<table style="width: 100%; border: none;"><tr><td style="border: none; padding: 0;">${leftHtml}</td><td style="border: none; padding: 0; text-align: right;">${rightHtml}</td></tr></table>`
      );
      continue;
    }

    processed.push(line);
  }

  return processed.join('\n');
}

/**
 * Recursively clean pdfMake node tree:
 * - Enforce black color and no underline for links
 * - Strip borders and padding from tables used by \hfill
 * - Filter out canvas divider lines (from hr)
 * - Filter out empty whitespace text nodes generated by htmlToPdfmake between HTML elements
 */
function cleanPdfNodes(nodes) {
  if (!nodes) return nodes;

  if (Array.isArray(nodes)) {
    const filtered = [];
    for (let i = 0; i < nodes.length; i++) {
      const item = nodes[i];
      // Strip canvas divider lines if any
      if (item && item.canvas) {
        continue;
      }
      cleanSinglePdfNode(item);
      // Filter out orphan whitespace text nodes unless carrying a page break
      if (item && typeof item.text === 'string' && item.text.trim() === '' && !item.pageBreak) {
        continue;
      }
      filtered.push(item);
    }
    return filtered;
  }

  if (typeof nodes === 'object') {
    if (nodes.canvas) return null;
    cleanSinglePdfNode(nodes);
    if (typeof nodes.text === 'string' && nodes.text.trim() === '' && !nodes.pageBreak) return null;
    return nodes;
  }

  return nodes;
}

function cleanSinglePdfNode(node) {
  if (!node || typeof node !== 'object') return;

  // Map html-to-pdfmake pageBreakBefore / pageBreakAfter to pdfMake pageBreak
  if (node.pageBreakBefore === 'always' || node.pageBreakBefore === true) {
    node.pageBreak = 'before';
    delete node.pageBreakBefore;
  }
  if (node.pageBreakAfter === 'always' || node.pageBreakAfter === true) {
    node.pageBreak = 'after';
    delete node.pageBreakAfter;
  }

  // If node is a pageBreak placeholder, neutralize its height and margins
  if (node.pageBreak && (node.text === '\u200B' || node.text === '​' || !node.text)) {
    node.fontSize = 0.1;
    node.lineHeight = 0;
    node.margin = [0, 0, 0, 0];
  }

  // Remove conflicting marginBottom so node.margin governs
  if (node.marginBottom !== undefined && node.margin) {
    delete node.marginBottom;
  }

  // Reset links to black and remove underline
  if (node.link) {
    node.color = '#000000';
    delete node.decoration;
  }
  if (node.color === 'blue' || node.color === '#0000ee' || node.color === '#1a0dab') {
    node.color = '#000000';
  }
  if (node.decoration === 'underline' && node.link) {
    delete node.decoration;
  }

  // Borderless table layout for \hfill
  if (node.table) {
    node.margin = [0, 0, 0, 0];
    node.layout = {
      hLineWidth: function () { return 0; },
      vLineWidth: function () { return 0; },
      paddingLeft: function () { return 0; },
      paddingRight: function () { return 0; },
      paddingTop: function () { return 0; },
      paddingBottom: function () { return 0; }
    };
    if (node.table.body) {
      for (let r = 0; r < node.table.body.length; r++) {
        const row = node.table.body[r];
        if (Array.isArray(row)) {
          for (let c = 0; c < row.length; c++) {
            cleanSinglePdfNode(row[c]);
          }
        }
      }
    }
  }

  // Children recursion
  if (node.text && Array.isArray(node.text)) {
    for (let i = 0; i < node.text.length; i++) {
      cleanSinglePdfNode(node.text[i]);
    }
  } else if (node.text && typeof node.text === 'object') {
    cleanSinglePdfNode(node.text);
  }

  if (node.stack && Array.isArray(node.stack)) {
    node.stack = cleanPdfNodes(node.stack);
  }
  if (node.columns && Array.isArray(node.columns)) {
    for (let i = 0; i < node.columns.length; i++) {
      cleanSinglePdfNode(node.columns[i]);
    }
  }
  if (node.ul && Array.isArray(node.ul)) {
    for (let i = 0; i < node.ul.length; i++) {
      cleanSinglePdfNode(node.ul[i]);
    }
  }
  if (node.ol && Array.isArray(node.ol)) {
    for (let i = 0; i < node.ol.length; i++) {
      cleanSinglePdfNode(node.ol[i]);
    }
  }
}

